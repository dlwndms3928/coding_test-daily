"""
- 정수 N이 입력되면 00시 00분 00초부터 N시 59분 59초까지의
    모든 시각 중에서 3이 하나라도 포함되는 모든 경우의 수를 구하는 프로그램 작성
    예를 들어 1을 입력했을 때 다음은 3이 하나라도 포함되어 있으므로 세어야 하는 시각
    - 00시 00분 03초
    - 00시 13분 30초

[입력조건]
- 첫째 줄에 정수 N이 입력된다
5
[출력조건]
- 00시 00분 00초부터 N시 59분 59초까지의 모든 시각중에서 3이 하나라도 포함되는
 모든 경우의 수를 출력
 11475
"""

N = int(input())
count = 0
for i in range(N + 1):
    if i in (3, 13, 23):
        count += 3600  # 60*60
    else:
        count += 1575
print(f"{count}")
